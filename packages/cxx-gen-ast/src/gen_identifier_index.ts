import { writeFileSync } from "node:fs";
import { cpy_header } from "./cpy_header.ts";
import * as tokens from "./tokens.ts";

const families = [
  ["TypeTrait", "BUILTIN_TYPE_TRAIT", tokens.BUILTIN_TYPE_TRAITS],
  [
    "UnaryType",
    "UNARY_BUILTIN_TYPE_TRAIT",
    tokens.UNARY_BUILTIN_TYPE_SPECIFIERS,
  ],
  ["Function", "BUILTIN_FUNCTION", tokens.BUILTIN_FUNCTIONS],
  ["Template", "BUILTIN_TEMPLATE", tokens.BUILTIN_TEMPLATES],
  ["WellKnown", "WELL_KNOWN_NAME", tokens.WELL_KNOWN_NAMES],
] as const;

// The low five bits distinguish ASCII letters irrespective of case. Choose the
// position that minimizes candidate comparisons for each spelling length.
const bucketCount = 32;
function bucketsFor(words: string[], ordinals: number[], length: number) {
  let best: number[][] = [];
  let position = 0;
  let bestCost = Infinity;
  let bestWorst = Infinity;
  for (let i = 0; i < length; ++i) {
    const buckets = Array.from({ length: bucketCount }, (): number[] => []);
    for (const ordinal of ordinals)
      buckets[words[ordinal].charCodeAt(i) % bucketCount].push(ordinal);
    const sizes = buckets.map((bucket) => bucket.length);
    const cost = sizes.reduce((sum, size) => sum + size * size, 0);
    const worst = Math.max(...sizes);
    if (cost < bestCost || (cost === bestCost && worst < bestWorst)) {
      bestCost = cost;
      bestWorst = worst;
      best = buckets;
      position = i;
    }
  }
  return { position, buckets: best };
}

export function gen_identifier_index({ output }: { output: string }) {
  // Zero denotes an ordinary identifier. Each family's remaining ordinals
  // follow its token enum, whose T_NONE also has value zero.
  const words = [""];
  const lines = [
    "// Generated by gen_identifier_index.ts",
    cpy_header,
    "#pragma once",
    "",
    "#include <cxx/token_fwd.h>",
    "",
    "#include <cstdint>",
    "",
    "namespace cxx::identifier_index {",
    "// clang-format off",
  ];
  for (const [family, , spellings] of families) {
    lines.push(`constexpr unsigned first${family} = ${words.length};`);
    words.push(...spellings);
  }
  lines.push(`constexpr unsigned end = ${words.length};`);
  if (
    new Set(words).size !== words.length ||
    words.slice(1).some((name) => !/^[A-Za-z_][A-Za-z0-9_]*$/.test(name))
  )
    throw new Error(
      "semantic identifier spellings must be unique ASCII identifiers",
    );

  const offsets = [0];
  for (const name of words) offsets.push(offsets.at(-1)! + name.length);
  const lengths = words.slice(1).map((word) => word.length);
  const min = Math.min(...lengths);
  const max = Math.max(...lengths);
  if (offsets.at(-1)! > 0xffff || max - 1 > 0xff)
    throw new Error(
      "semantic identifier spelling offsets or positions exceed the index width",
    );

  const positions: number[] = [];
  const starts = [0];
  const candidates: number[] = [];
  for (let length = min; length <= max; ++length) {
    const ordinals = words.flatMap((word, i) =>
      word.length === length ? [i] : [],
    );
    const { position, buckets } = bucketsFor(words, ordinals, length);
    positions.push(position);
    for (const bucket of buckets) {
      candidates.push(...bucket);
      starts.push(candidates.length);
    }
  }

  lines.push(`constexpr unsigned minLength = ${min};`);
  lines.push(`constexpr unsigned bucketCount = ${bucketCount};`, "");
  lines.push(
    "#define IDENTIFIER_SPELLING(id, spelling) spelling",
    "constexpr char spellings[] =",
  );
  for (const [, macro] of families)
    lines.push(`    FOR_EACH_${macro}(IDENTIFIER_SPELLING)`);
  lines.push("    ;", "#undef IDENTIFIER_SPELLING");
  function array(type: string, name: string, values: number[]) {
    lines.push("", `constexpr std::${type} ${name}[] = {`);
    for (let i = 0; i < values.length; i += 16)
      lines.push(`    ${values.slice(i, i + 16).join(", ")},`);
    lines.push("};");
  }
  array("uint16_t", "offsets", offsets);
  array("uint8_t", "positions", positions);
  array("uint16_t", "starts", starts);
  array("uint16_t", "candidates", candidates);
  lines.push("// clang-format on", "}  // namespace cxx::identifier_index", "");
  writeFileSync(output, lines.join("\n"));
}
